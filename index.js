//phase 1

// Count frequency of each language family
const familyCounts = d3.rollup(
  myData,
  v => v.length,
  d => d.family
);

// Convert Map to array
const familyArray = Array.from(familyCounts, ([family, count]) => ({
  family,
  count
}));

// Sort descending
familyArray.sort((a, b) => b.count - a.count);

const width = 800;
const height = 500;
const margin = { top: 60, right: 30, bottom: 120, left: 80 };

const svg = d3.select("#bar-chart")
  .append("svg")
  .attr("width", width)
  .attr("height", height);

// Scales
const x = d3.scaleBand()
  .domain(familyArray.map(d => d.family))
  .range([margin.left, width - margin.right])
  .padding(0.15);

const y = d3.scaleLinear()
  .domain([0, d3.max(familyArray, d => d.count)])
  .nice()
  .range([height - margin.bottom, margin.top]);

// Create bars
const bars = svg.selectAll("rect")
  .data(familyArray)
  .join("rect")
  .attr("x", d => x(d.family))
  .attr("width", x.bandwidth())
  .attr("y", height - margin.bottom)
  .attr("height", 0)
  .attr("fill", "#6baed6")
  .on("click", function(event, d) {

    const isActive = d3.select(this).attr("fill") === "#ff7f0e";

    // Reset all bars
    bars.attr("fill", "#6baed6");

    // Highlight selected
    if (!isActive) {
      d3.select(this).attr("fill", "#ff7f0e");
    }
  });

// Animate bars
bars.transition()
  .duration(800)
  .attr("y", d => y(d.count))
  .attr("height", d => height - margin.bottom - y(d.count));

// X Axis
svg.append("g")
  .attr("transform", `translate(0,${height - margin.bottom})`)
  .call(d3.axisBottom(x))
  .selectAll("text")
  .attr("transform", "rotate(-45)")
  .style("text-anchor", "end")
  .style("font-size", "11px");

// Y Axis
svg.append("g")
  .attr("transform", `translate(${margin.left},0)`)
  .call(d3.axisLeft(y));

// Lighten axis lines
svg.selectAll(".domain, .tick line")
  .attr("stroke", "#ccc")
  .attr("stroke-width", 1);

// Title
svg.append("text")
  .attr("x", width / 2)
  .attr("y", 35)
  .attr("text-anchor", "middle")
  .style("font-size", "22px")
  .style("font-weight", "600")
  .text("Distribution of Languages by Family");

// X Label
svg.append("text")
  .attr("x", width / 2)
  .attr("y", height - 40)
  .attr("text-anchor", "middle")
  .style("font-size", "14px")
  .text("Language Family");

// Correct Y Label
svg.append("text")
  .attr("transform", "rotate(-90)")
  .attr("x", -height / 2)
  .attr("y", 30)
  .attr("text-anchor", "middle")
  .style("font-size", "14px")
  .text("Number of Languages in Family");


//phase 2

const pieWidth = 500;
const pieHeight = 500;
const radius = 200;

// Add margins so labels fit
const pieMargin = { top: 60, right: 200, bottom: 60, left: 60 };

const pieSvg = d3.select("#pie-chart")
  .append("svg")
  .attr("width", pieWidth + pieMargin.left + pieMargin.right)
  .attr("height", pieHeight + pieMargin.top + pieMargin.bottom)
  .append("g")
  .attr("transform",
    `translate(${pieWidth / 2 + pieMargin.left},
               ${pieHeight / 2 + pieMargin.top})`
  );

// Pie generator
const pie = d3.pie()
  .value(d => d.count);

const pieData = pie(familyArray);

// Arcs
const arc = d3.arc()
  .innerRadius(0)
  .outerRadius(radius);

const labelArc = d3.arc()
  .innerRadius(radius + 25)
  .outerRadius(radius + 25);

// Draw slices
pieSvg.selectAll("path")
  .data(pieData)
  .join("path")
  .attr("d", arc)
  .attr("fill", (d, i) => d3.schemeCategory10[i % 10])
  .on("click", function(event, d) {

    const proportion = (d.data.count / myData.length * 100).toFixed(1);

    d3.select("#pie-info")
      .text(`${d.data.family}: ${proportion}% of languages in dataset`);
  });

// Labels outside pie
pieSvg.selectAll("text")
  .data(pieData)
  .join("text")
  .attr("transform", d => `translate(${labelArc.centroid(d)})`)
  .attr("text-anchor", d =>
    (d.startAngle + d.endAngle) / 2 < Math.PI ? "start" : "end"
  )
  .attr("alignment-baseline", "middle")
  .style("font-size", "11px")
  .text(d => d.data.family);

// Pie Title
d3.select("#pie-chart svg")
  .append("text")
  .attr("x", (pieWidth + pieMargin.left + pieMargin.right) / 2)
  .attr("y", 30)
  .attr("text-anchor", "middle")
  .style("font-size", "20px")
  .style("font-weight", "600")
  .text("Proportion of Language Families");